from pathlib import Path
import json

import log
from preprocess import preprocess
import model

import pandas as pd


### config #####################################################################################################################################################
with open(Path(__file__).parent / "config.json", "r", encoding="utf-8") as f: data_files = json.load(f).get("data_files", {})
################################################################################################################################################################


### data #######################################################################################################################################################
@log.load_data
def load_data():
    return {name: pd.read_excel(Path(__file__).parent / "data" / filename) for name, filename in data_files.items()}
################################################################################################################################################################


### exec #######################################################################################################################################################
################################################################################################################################################################

def run(dict_data):
    data_processed = preprocess(dict_data)
    m, candidates, market_cands = model.build(data_processed)
    model.solve(data_processed, m, candidates)
    result = model.extract(data_processed, m, candidates)
    model.export(result)
    return result


if __name__ == "__main__":
    run(load_data())

